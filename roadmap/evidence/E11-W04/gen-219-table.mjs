// E11-W04 step 1: compares round 1's 219 keys (E11-W02's 20-es-en-review.md) with what
// `check-es-actions.mjs` flags on the pre-round-1 catalog (log 02), and writes the before/after
// table from log 02 («old») and the current es catalog («new»).
// Usage (repository root): node roadmap/evidence/E11-W04/gen-219-table.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const evidence = "roadmap/evidence/E11-W04";
const review = readFileSync("roadmap/evidence/E11-W02/20-es-en-review.md", "utf8");
const section = review
  .split("## `es`: imperative → infinitive (219 lines)")[1]
  .split("## `es`: word choice")[0];
const rows = [...section.matchAll(/^\| `([^`]+)` \| (.*) \| (.*) \|$/gmu)].map((match) => ({
  after: match[3],
  before: match[2],
  key: match[1],
}));

const flagged = new Map();
for (const line of readFileSync(`${evidence}/02-es-actions-pre-round1-red.log`, "utf8").split("\n")) {
  if (!/^[a-z-]+:\S+ · «/u.test(line)) continue;
  const index = line.indexOf(" · «");
  flagged.set(line.slice(0, index), line.slice(index + 4, -1));
}

const current = new Map();
const directory = "packages/i18n/src/locales/es";
for (const file of readdirSync(directory).sort()) {
  const namespace = path.basename(file, ".json");
  const walk = (value, prefix) => {
    if (typeof value === "string") {
      current.set(`${namespace}:${prefix}`, value);
      return;
    }
    for (const [key, child] of Object.entries(value)) walk(child, prefix ? `${prefix}.${key}` : key);
  };
  walk(JSON.parse(readFileSync(path.join(directory, file), "utf8")), "");
}

const missing = rows.filter((row) => !flagged.has(row.key));
const extra = [...flagged.keys()].filter((key) => !rows.some((row) => row.key === key));
const log = [
  `table keys (roadmap/evidence/E11-W02/20-es-en-review.md): ${rows.length} (${new Set(rows.map((row) => row.key)).size} unique)`,
  `flagged by log 02 (the es catalog of 85c4b469~1): ${flagged.size}`,
  `${rows.length - missing.length} of ${rows.length} flagged, ${missing.length} missing${missing.length > 0 ? `: ${missing.map((row) => row.key).join(", ")}` : ""}`,
  `flagged value = the table's «before»: ${rows.filter((row) => flagged.get(row.key) === row.before).length} of ${rows.length}`,
  `current value = the table's «after»: ${rows.filter((row) => current.get(row.key) === row.after).length} of ${rows.length}`,
  `flagged before round 1 but not in the table: ${extra.length}`,
  ...extra.map((key) => `  ${key} · «${flagged.get(key)}» → now «${current.get(key)}»`),
  "",
].join("\n");
writeFileSync(`${evidence}/02b-es-actions-219-diff.log`, log);

const table = [
  "# E11-W04 · the 219 es labels of E11-W02 round 1, all flagged by the check",
  "",
  "Generated by `gen-219-table.mjs` from `02-es-actions-pre-round1-red.log` (`node scripts/check-es-actions.mjs --locales <the es catalog of 85c4b469~1>`; «old» is the flagged value) and the current `packages/i18n/src/locales/es` («new»). Keys and order: the table of `roadmap/evidence/E11-W02/20-es-en-review.md`.",
  "",
  `**${rows.length - missing.length} of ${rows.length} flagged, ${missing.length} missing.** These strings are not edited by E11-W04 (E132, E137).`,
  "",
  "| key | old (flagged) | new |",
  "|---|---|---|",
  ...rows.map(
    (row) =>
      `| \`${row.key}\` | ${flagged.get(row.key) ?? "(not flagged)"} | ${current.get(row.key) ?? "(missing)"} |`,
  ),
  "",
].join("\n");
writeFileSync(`${evidence}/02-es-actions-219.md`, table);
console.log(log);
